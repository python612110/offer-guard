export interface ContractExcerpt {
  page: number;
  text: string;
}

export function extractContractOverview(pages: DocumentPage[]) {
  const fields = overviewSections.map(({ title, fields }) => ({
    title,
    facts: fields.map(([label, pattern]) => ({
      label,
      pattern,
      excerpts: [] as ContractExcerpt[],
      count: 0,
    })),
  }));
  for (const page of pages) {
    // Keep semicolon-linked qualifiers together (e.g. salary plus its conditions).
    for (const part of page.text.matchAll(/[^。！？\r\n]+[。！？]?/g)) {
      const text = part[0].trim();
      if (!text) continue;
      for (const section of fields) {
        for (const field of section.facts) {
          if (
            !field.pattern.test(text) ||
            field.excerpts.some((entry) => entry.text === text)
          )
            continue;
          if (
            field.label === "工资总额与支付周期" &&
            /试用期/.test(text) &&
            !/转正/.test(text)
          )
            continue;
          field.count++;
          // Bound the initial render for unusually long documents.
          if (field.excerpts.length < 8) {
            field.excerpts.push({ page: page.number, text });
          }
        }
      }
    }
  }
  return fields.map(({ title, facts }) => ({
    title,
    facts: facts.map(({ label, excerpts, count }) => ({
      label,
      excerpts,
      count,
    })),
  }));
}
